from google.colab import files
uploaded = files.upload()

import cv2
import numpy as np
import matplotlib.pyplot as plt
import random
import math

# Step 1: Read uploaded image
filename = next(iter(uploaded))
image = cv2.imread(filename)

if image is None:
    raise ValueError("Unable to read the uploaded image.")

gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

# Step 2: Fitness function: Otsu between-class variance
def fitness(threshold):
    background = gray[gray <= threshold]
    foreground = gray[gray > threshold]

    if len(background) == 0 or len(foreground) == 0:
        return 0.0
#CALCULATING PROPORTION
    w0 = len(background) / gray.size
    w1 = len(foreground) / gray.size
#AVERAGE GRAY SCALE INTENSITY IN EACH GROUP
    mean0 = np.mean(background)
    mean1 = np.mean(foreground)

    return w0 * w1 * (mean0 - mean1) ** 2

# Step 3: Simulated Annealing algorithm
def simulated_annealing():
    current = random.randint(0, 255)
    current_score = fitness(current)

    best = current
    best_score = current_score

    temperature = 100.0
    cooling_rate = 0.95
    min_temperature = 0.1

    while temperature > min_temperature:
        neighbor = int(np.clip(
            current + random.randint(-10, 10), 0, 255
        ))

        neighbor_score = fitness(neighbor)
        difference = neighbor_score - current_score

        if difference > 0 or random.random() < math.exp(
            difference / temperature
        ):
            current = neighbor
            current_score = neighbor_score

        if current_score > best_score:
            best = current
            best_score = current_score

        temperature *= cooling_rate

    return best, best_score

# Step 4: Optimize threshold
optimal_threshold, best_score = simulated_annealing()

# Step 5: Segment image
_, segmented = cv2.threshold(
    gray, optimal_threshold, 255, cv2.THRESH_BINARY
)

print("Optimal threshold:", optimal_threshold)
print("Best fitness:", best_score)

# Step 6: Display output
plt.figure(figsize=(15, 4))

plt.subplot(1, 3, 1)
plt.imshow(gray, cmap="gray")
plt.title("Original Grayscale Image")
plt.axis("off")

plt.subplot(1, 3, 2)
plt.imshow(segmented, cmap="gray")
plt.title(f"SA Segmentation (T={optimal_threshold})")
plt.axis("off")

plt.subplot(1, 3, 3)
plt.hist(gray.ravel(), bins=256, range=(0, 256))
plt.axvline(optimal_threshold, linestyle="--",
            label=f"Threshold = {optimal_threshold}")
plt.title("Grayscale Histogram")
plt.legend()

plt.tight_layout()
plt.show()

